type GoKind = 'http-server' | 'cli' | 'generic';

interface GoDetection {
  kind: GoKind;
  framework: string;
  /** `go build` target for the server binary, e.g. "." or "./cmd/server". */
  buildTarget: string;
}

/** Sanitize an arbitrary string into a safe Go identifier fragment. */
function goIdent(raw: string): string {
  const cleaned = raw.replace(/[^a-zA-Z0-9]+/g, '_').replace(/^_+|_+$/g, '');
  if (cleaned === '') return 'root';
  return /^[0-9]/.test(cleaned) ? `_${cleaned}` : cleaned;
}

/**
 * A single `go test -json` event. We only consume the fields we need.
 * @see https://pkg.go.dev/cmd/test2json
 */
interface GoTestEvent {
  Action?: string;
  Package?: string;
  Test?: string;
  Output?: string;
}

/**
 * Parse the newline-delimited JSON stream emitted by `go test -json` into the
 * framework's normalized suite/test model. One suite per package; package-level
 * events (no `Test` field) are folded into a synthetic `<package>` test only
 * when they fail, so a green run reports just its real tests.
 */
export function parseGoTestJson(stdout: string): TestSuiteResult[] {
  const suites = new Map<string, TestSuiteResult>();
  const output = new Map<string, string[]>(); // key: pkg\x00test

  const suiteFor = (pkg: string): TestSuiteResult => {
    let suite = suites.get(pkg);
    if (suite === undefined) {
      suite = { file: pkg, status: 'passed', duration: 0, tests: [] };
      suites.set(pkg, suite);
    }
    return suite;
  };

  for (const line of stdout.split('\n')) {
    const trimmed = line.trim();
    if (trimmed === '' || !trimmed.startsWith('{')) continue;
    let event: GoTestEvent;
    try {
      event = JSON.parse(trimmed) as GoTestEvent;
    } catch {
      continue;
    }
    const pkg = event.Package ?? '<unknown>';
    const key = `${pkg}\x00${event.Test ?? ''}`;

    if (event.Action === 'output' && typeof event.Output === 'string') {
      const buf = output.get(key) ?? [];
      buf.push(event.Output);
      output.set(key, buf);
      continue;
    }

    if (event.Action !== 'pass' && event.Action !== 'fail' && event.Action !== 'skip') {
      continue;
    }

    const suite = suiteFor(pkg);
    const status: TestCaseResult['status'] =
      event.Action === 'pass' ? 'passed' : event.Action === 'skip' ? 'skipped' : 'failed';

    if (event.Test === undefined || event.Test === '') {
      // Package-level result: only surface failures (e.g. build/compile errors).
      if (status === 'failed') {
        suite.status = 'failed';
        suite.tests.push({
          name: `${pkg} (package)`,
          status: 'failed',
          failureMessages: [(output.get(key) ?? []).join('').slice(0, 2000)],
        });
      }
      continue;
    }

    if (status === 'failed') suite.status = 'failed';
    suite.tests.push({
      name: event.Test,
      status,
      failureMessages: status === 'failed' ? [(output.get(key) ?? []).join('').slice(0, 2000)] : [],
    });
  }

  return [...suites.values()];
}

