export class GoGenerator implements E2ETestGenerator {
  readonly id = 'go';

  async detectProjectStructure(root: string): Promise<ProjectStructure | null> {
    const detection = await this.detect(root);
    if (detection === null) return null;
    return { language: 'go', framework: detection.framework, testTool: 'go test', root };
  }

  analyzeImpact(changedFiles: string[], config: ResolvedE2EConfig, projectRoot?: string): ImpactAnalysisResult {
    const filesToAnalyze = config.recursiveAnalysisEnabled
      ? new RecursiveImpactAnalyzer().analyze(
          changedFiles,
          projectRoot ?? process.cwd(),
          'go',
          { maxDepth: config.maxRecursiveDepth },
        )
      : changedFiles;
    const packages = new Set<string>();
    for (const file of filesToAnalyze) {
      const normalized = file.replace(/\\/g, '/');
      if (!normalized.endsWith('.go') || normalized.endsWith('_test.go')) continue;
      const slash = normalized.lastIndexOf('/');
      packages.add(slash === -1 ? '.' : normalized.slice(0, slash));
    }

    const affected: AffectedTool[] = [];
    for (const pkg of packages) {
      const priority: E2EPriority = config.criticalTools.includes(pkg) ? 'critical' : 'important';
      if (config.strategy === 'critical-only' && priority !== 'critical') continue;
      affected.push({ toolId: pkg, priority });
    }

    if (affected.length === 0 && config.strategy === 'always') {
      affected.push({ toolId: 'general', priority: 'nice-to-have' });
    }

    return { affectedTools: affected };
  }

  resolveGeneratedTestDir(config: ResolvedE2EConfig): string {
    // The Go toolchain ignores directories whose name begins with "." or "_"
    // (even when named explicitly), so the default `.ody-code/...` path is
    // unusable. Fall back to a module-internal, non-ignored directory.
    const segments = config.generatedTestDir.replace(/\\/g, '/').split('/').filter((s) => s.length > 0);
    const ignored = segments.some((s) => s.startsWith('.') || s.startsWith('_'));
    return ignored ? 'e2e_generated' : config.generatedTestDir;
  }

  async generateTestsForFeature(feature: Feature, _outputDir: string): Promise<TestFile[]> {
    const detection =
      (await this.detect(feature.projectRoot)) ??
      { kind: 'generic' as GoKind, framework: 'generic', buildTarget: '.' };
    const ident = goIdent(feature.toolId);
    const relativePath = `${ident.toLowerCase()}_e2e_test.go`;

    const content =
      detection.kind === 'http-server'
        ? this.renderHttpServerTest(ident, feature, detection.buildTarget)
        : this.renderGenericTest(ident, feature, detection.kind);

    return [{ relativePath, content }];
  }

  async runTests(absoluteTestPaths: string[], ctx: RunContext): Promise<TestSuiteResult[]> {
    if (absoluteTestPaths.length === 0) return [];
    const { kaos, config, projectRoot, signal } = ctx;
    // `go test` runs by package directory, not by file: run every unique dir
    // exactly once in a single invocation so we never double-count a package.
    const dirs = [...new Set(absoluteTestPaths.map((p) => this.relativeDir(projectRoot, p)))];
    const packageArgs = dirs.map((d) => `./${d}/`);
    const timeoutSeconds = Math.max(1, Math.ceil(config.testTimeout / 1000));
    const k = kaos.withCwd(projectRoot);

    const proc = await k.exec(
      'go', 'test', '-json',
      '-tags', 'e2e',
      `-timeout=${timeoutSeconds}s`,
      ...packageArgs,
    );

    const onAbort = () => { void proc.kill(); };
    if (signal?.aborted) onAbort();
    else signal?.addEventListener('abort', onAbort, { once: true });

    const stdoutChunks: Buffer[] = [];
    const stderrChunks: Buffer[] = [];
    proc.stdout.on('data', (chunk: Buffer) => stdoutChunks.push(chunk));
    proc.stderr.on('data', (chunk: Buffer) => stderrChunks.push(chunk));

    try {
      await proc.wait();
    } finally {
      signal?.removeEventListener('abort', onAbort);
    }

    const stdout = Buffer.concat(stdoutChunks).toString('utf-8');
    const suites = parseGoTestJson(stdout);
    if (suites.length > 0) return suites;

    // No parseable JSON usually means `go test` failed before running (e.g. a
    // compile error printed to stderr). Surface it as a single failed suite.
    const stderr = Buffer.concat(stderrChunks).toString('utf-8');
    return [{
      file: packageArgs.join(' '),
      status: 'failed' as const,
      duration: 0,
      tests: [{
        name: 'go test failed to run',
        status: 'failed' as const,
        failureMessages: [(stderr || stdout).slice(0, 2000)],
      }],
    }];
  }

  private renderHttpServerTest(ident: string, feature: Feature, buildTarget: string): string {
    return HTTP_SERVER_TEMPLATE
      .replaceAll('{{ident}}', ident)
      .replaceAll('{{moduleRoot}}', JSON.stringify(feature.projectRoot))
      .replaceAll('{{buildTarget}}', JSON.stringify(buildTarget));
  }

  private renderGenericTest(ident: string, feature: Feature, kind: GoKind): string {
    return GENERIC_TEMPLATE
      .replaceAll('{{ident}}', ident)
      .replaceAll('{{kind}}', kind)
      .replaceAll('{{toolId}}', feature.toolId);
  }

  /** Convert an absolute generated-file path into a module-relative dir. */
  private relativeDir(projectRoot: string, absoluteFile: string): string {
    const root = projectRoot.replace(/\\/g, '/').replace(/\/$/, '');
    const file = absoluteFile.replace(/\\/g, '/');
    const withoutRoot = file.startsWith(root + '/') ? file.slice(root.length + 1) : file;
    const slash = withoutRoot.lastIndexOf('/');
    return slash === -1 ? '.' : withoutRoot.slice(0, slash);
  }

  /** Detect whether `root` is a Go module and classify its shape. */
  private async detect(root: string): Promise<GoDetection | null> {
    const { existsSync, readFileSync, readdirSync } = await import('node:fs');
    if (!existsSync(join(root, 'go.mod'))) return null;

    const buildTarget = this.findBuildTarget(existsSync, readdirSync, readFileSync, root);

    try {
      const mod = readFileSync(join(root, 'go.mod'), 'utf-8');
      if (/gin-gonic\/gin/.test(mod)) return { kind: 'http-server', framework: 'gin', buildTarget };
      if (/labstack\/echo/.test(mod)) return { kind: 'http-server', framework: 'echo', buildTarget };
      if (/gofiber\/fiber/.test(mod)) return { kind: 'http-server', framework: 'fiber', buildTarget };
    } catch {
      // fall through to source scan
    }

    const goFiles = this.collectGoFiles(readdirSync, root, 300);
    let hasMain = existsSync(join(root, 'cmd'));
    for (const file of goFiles) {
      let content: string;
      try {
        content = readFileSync(file, 'utf-8');
      } catch {
        continue;
      }
      if (/"net\/http"/.test(content) && /(ListenAndServe|http\.Serve|\.Run\()/.test(content)) {
        return { kind: 'http-server', framework: 'net-http', buildTarget };
      }
      if (/package\s+main/.test(content) && /func\s+main\s*\(/.test(content)) {
        hasMain = true;
      }
    }

    return hasMain
      ? { kind: 'cli', framework: 'cli', buildTarget }
      : { kind: 'generic', framework: 'generic', buildTarget };
  }

  /**
   * Best-effort `go build` target for the server entrypoint. Prefers a `main`
   * package at the module root, then the common single `./cmd/<name>` layout,
   * falling back to "." (which the generated TODO comment tells the user to fix).
   */
  private findBuildTarget(
    existsSync: typeof import('node:fs').existsSync,
    readdirSync: typeof import('node:fs').readdirSync,
    readFileSync: typeof import('node:fs').readFileSync,
    root: string,
  ): string {
    try {
      for (const entry of readdirSync(root, { withFileTypes: true })) {
        if (entry.isFile() && entry.name.endsWith('.go') && !entry.name.endsWith('_test.go')) {
          try {
            if (/package\s+main/.test(readFileSync(join(root, entry.name), 'utf-8'))) return '.';
          } catch {
            // ignore unreadable file
          }
        }
      }
    } catch {
      // ignore unreadable root
    }
    const cmdDir = join(root, 'cmd');
    if (existsSync(cmdDir)) {
      try {
        const subs = readdirSync(cmdDir, { withFileTypes: true }).filter((e) => e.isDirectory());
        if (subs.length === 1) return `./cmd/${subs[0]!.name}`;
      } catch {
        // ignore unreadable cmd dir
      }
    }
    return '.';
  }

  /** Bounded recursive walk collecting `.go` source files (skips vendored/hidden dirs). */
  private collectGoFiles(
    readdirSync: typeof import('node:fs').readdirSync,
    root: string,
    limit: number,
  ): string[] {
    const results: string[] = [];
    const stack = [root];
    while (stack.length > 0 && results.length < limit) {
      const dir = stack.pop()!;
      const entries = (() => {
        try {
          return readdirSync(dir, { withFileTypes: true });
        } catch {
          return [];
        }
      })();
      for (const entry of entries) {
        const name = entry.name;
        if (entry.isDirectory()) {
          if (name.startsWith('.') || name.startsWith('_') || name === 'vendor' || name === 'node_modules') {
            continue;
          }
          stack.push(join(dir, name));
        } else if (name.endsWith('.go') && !name.endsWith('_test.go')) {
          results.push(join(dir, name));
          if (results.length >= limit) break;
        }
      }
    }
    return results;
  }
}
